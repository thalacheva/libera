const newDrill = (): Drill => {
  const kind = randInt(0, 4);
  if (kind === 0) {
    const [z, a] = pick(NUCLIDES);
    return {
      tex: nuclide(z, a),
      ask: 'Колко неутрона има ядрото?',
      num: a - z,
      den: 1,
      steps: [`Долният индекс е $Z = ${z}$ (протони), горният – $A = ${a}$ (протони + неутрони).`, `$N = A - Z = ${a} - ${z} = ${a - z}$`],
    };
  }
  if (kind === 1) {
    const [z, a, q] = pick(IONS);
    return {
      tex: nuclide(z, a, chargeTex(q)),
      ask: 'Колко електрона има йонът?',
      num: z - q,
      den: 1,
      steps: [
        `Неутралният атом има $${z}$ електрона – колкото протоните.`,
        q > 0 ? `Зарядът $${q}+$ значи, че са отдадени ${q}: $${z} - ${q} = ${z - q}$` : `Зарядът $${-q}-$ значи, че са приети ${-q}: $${z} + ${-q} = ${z - q}$`,
      ],
    };
  }
  if (kind === 2 || kind === 3) {
    const z = randInt(1, 20);
    const s = shells(z);
    const el = byZ(z);
    return kind === 2
      ? {
          tex: `\\mathrm{${el.symbol}}\\ (Z = ${z})`,
          ask: 'Колко електрона има на външния слой?',
          num: s[s.length - 1],
          den: 1,
          steps: [`Разпределяме ${z} електрона по слоевете (2, 8, 8, 2): $${s.join(',\\ ')}$`, `На външния слой има $${s[s.length - 1]}$.`],
        }
      : {
          tex: `\\mathrm{${el.symbol}}\\ (Z = ${z})`,
          ask: 'В кой период е елементът?',
          num: s.length,
          den: 1,
          steps: [`Слоевете: $${s.join(',\\ ')}$ – общо ${s.length}.`, `Номерът на периода е равен на броя на слоевете: период ${s.length}.`],
        };
  }
  // Средна атомна маса от два изотопа (масите – колкото масовите числа)
  const [a1, a2] = pick([
    [10, 11],
    [6, 7],
    [35, 37],
    [63, 65],
    [79, 81],
    [24, 26],
    [20, 22],
  ]);
  const p = pick([10, 20, 25, 40, 60, 75, 80, 90]);
  return {
    tex: `{}^{${a1}}\\mathrm{X}: ${p}\\%,\\quad {}^{${a2}}\\mathrm{X}: ${100 - p}\\%`,
    ask: 'Средна атомна маса? (масите на изотопите приеми равни на масовите числа)',
    num: a1 * p + a2 * (100 - p),
    den: 100,
    steps: [`$A_r = ${dec(p / 100)} \\cdot ${a1} + ${dec((100 - p) / 100)} \\cdot ${a2} = ${dec((a1 * p + a2 * (100 - p)) / 100)}$`, 'Резултатът е по-близо до по-разпространения изотоп.'],
  };
};


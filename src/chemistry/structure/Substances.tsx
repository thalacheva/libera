/** Десетично число в LaTeX: 0.45 → 0{,}45. */
const dec = (v: number) => v.toLocaleString('en-US', { maximumSignificantDigits: 6, useGrouping: false }).replace('.', '{,}');
/** Десетично число като текст: 0.45 → 0,45. */
const decText = (v: number) => dec(v).replace('{,}', ',');
const g = (m: number) => `${dec(m)}\\ \\mathrm{g}`;

const newDrill = (): Drill => {
  const kind = randInt(0, 5);
  if (kind === 0) {
    // Масова част от масите на солта и водата; общата маса дава крайна десетична дроб
    const total = pick([100, 200, 250, 400, 500]);
    const salt = pick([5, 10, 15, 20, 25, 30, 40, 50].filter(s => s < total / 2));
    return {
      tex: `${g(salt)}\\ \\text{сол} + ${g(total - salt)}\\ \\text{вода}`,
      ask: 'Масова част на солта, %?',
      num: salt * 100,
      den: total,
      steps: [`Масата на разтвора е $${salt} + ${total - salt} = ${total}\\ \\mathrm{g}$ – делим на нея, не само на водата.`, `$w = \\frac{${salt}}{${total}} \\cdot 100\\% = ${dec((salt * 100) / total)}\\%$`],
    };
  }
  if (kind === 1 || kind === 2) {
    const m = pick([50, 150, 200, 250, 300, 400, 500]);
    const w = pick([2, 4, 5, 8, 10, 12, 15, 20, 25]);
    const salt = (m * w) / 100;
    return kind === 1
      ? {
          tex: `${g(m)}\\ \\text{разтвор},\\ w = ${w}\\%`,
          ask: 'Колко грама сол има в него?',
          num: m * w,
          den: 100,
          steps: [`$m_{\\text{сол}} = w \\cdot m_{\\text{р-р}} = ${dec(w / 100)} \\cdot ${m} = ${dec(salt)}\\ \\mathrm{g}$`],
        }
      : {
          tex: `${g(m)}\\ \\text{разтвор},\\ w = ${w}\\%`,
          ask: 'Колко грама вода са нужни, за да го приготвиш?',
          num: m * (100 - w),
          den: 100,
          steps: [`Сол: $${dec(w / 100)} \\cdot ${m} = ${dec(salt)}\\ \\mathrm{g}$`, `Вода: $${m} - ${dec(salt)} = ${dec(m - salt)}\\ \\mathrm{g}$`],
        };
  }
  if (kind === 3) {
    const [rf, front] = pick([
      [0.25, 8],
      [0.3, 8],
      [0.4, 5],
      [0.5, 6],
      [0.6, 5],
      [0.75, 6],
      [0.8, 10],
      [0.45, 10],
    ]);
    const spot = rf * front;
    return {
      tex: 'R_f = ?',
      ask: `Петното е на ${decText(spot)} cm от стартовата линия, а фронтът на разтворителя – на ${front} cm.`,
      num: Math.round(rf * 100),
      den: 100,
      steps: [`$R_f = \\frac{${dec(spot)}\\ \\mathrm{cm}}{${front}\\ \\mathrm{cm}} = ${dec(rf)}$`],
    };
  }
  if (kind === 4) {
    // Смесване на два разтвора; общата маса е 200, 400 или 500 g
    const [m1, m2] = pick([
      [100, 100],
      [200, 200],
      [100, 300],
      [300, 100],
      [200, 300],
      [300, 200],
    ]);
    const [w1, w2] = pick([
      [5, 15],
      [10, 30],
      [4, 20],
      [20, 5],
      [30, 10],
      [8, 12],
    ]);
    const s = (m1 * w1 + m2 * w2) / 100;
    return {
      tex: `${g(m1)}\\ (${w1}\\%) + ${g(m2)}\\ (${w2}\\%)`,
      ask: 'Масова част на сместа, %?',
      num: m1 * w1 + m2 * w2,
      den: m1 + m2,
      steps: [
        `Сол: $${dec(w1 / 100)} \\cdot ${m1} + ${dec(w2 / 100)} \\cdot ${m2} = ${dec(s)}\\ \\mathrm{g}$`,
        `$w = \\frac{${dec(s)}}{${m1 + m2}} \\cdot 100\\% = ${dec((s * 100) / (m1 + m2))}\\%$ – между ${w1}% и ${w2}%, по-близо до разтвора, който е повече.`,
      ],
    };
  }
  // Изпаряване: солта остава, масата на разтвора намалява k пъти
  const m = pick([200, 300, 400, 500]);
  const w1 = pick([2, 4, 5]);
  const k = pick([2, 4, 5]);
  return {
    tex: `${g(m)}:\\ ${w1}\\% \\to ${w1 * k}\\%`,
    ask: 'Колко грама вода трябва да се изпарят?',
    num: m * (k - 1),
    den: k,
    steps: [
      `Сол: $${dec(w1 / 100)} \\cdot ${m} = ${dec((m * w1) / 100)}\\ \\mathrm{g}$ – при изпаряването тя остава.`,
      `Новата маса на разтвора: $\\frac{${dec((m * w1) / 100)}}{${dec((w1 * k) / 100)}} = ${dec(m / k)}\\ \\mathrm{g}$`,
      `Изпарява се $${m} - ${dec(m / k)} = ${dec(m - m / k)}\\ \\mathrm{g}$ вода.`,
    ],
  };
};


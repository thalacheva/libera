const gcd = (a: number, b: number): number => (b === 0 ? a : gcd(b, a % b));
const en100 = (s: string) => Math.round((bySymbol.get(s)!.en ?? 0) * 100);
const dec = (v: number) => v.toFixed(2).replace('.', '{,}');

const newDrill = (): Drill => {
  const kind = randInt(0, 5);
  if (kind === 0) {
    const [s, name, v] = pick(MAIN);
    return {
      tex: `\\mathrm{${s}}`,
      ask: `Колко валентни електрона има атомът на ${name}?`,
      num: v,
      den: 1,
      steps: [`При елементите от главните групи броят на валентните електрони е равен на последната цифра на номера на групата: ${s} е в група ${v > 2 ? 10 + v : v}.`],
    };
  }
  if (kind === 1) {
    const [s, name, v] = pick(MAIN.filter(([s]) => !['C', 'Si'].includes(s)));
    const charge = v <= 3 ? v : v - 8;
    return {
      tex: `\\mathrm{${s}} \\to \\mathrm{${s}^{?}}`,
      ask: `Какъв е зарядът на йона на ${name}? (отрицателния въведи като −2)`,
      num: charge,
      den: 1,
      steps: [
        charge > 0
          ? `Металът отдава своите ${v} валентни електрона и остава с октета на предишния благороден газ: заряд $+${charge}$.`
          : `Неметалът има ${v} валентни електрона и приема още ${8 - v} до октет: заряд $${charge}$.`,
      ],
    };
  }
  if (kind === 2) {
    const [a, b] = pick([
      ['H', 'Cl'],
      ['Na', 'Cl'],
      ['H', 'O'],
      ['C', 'O'],
      ['N', 'H'],
      ['K', 'F'],
      ['Mg', 'O'],
      ['C', 'H'],
      ['Ca', 'Cl'],
      ['S', 'O'],
      ['Li', 'Br'],
      ['H', 'F'],
    ]);
    const d = Math.abs(en100(a) - en100(b));
    return {
      tex: `\\Delta\\chi(\\mathrm{${a}{-}${b}}) = ?`,
      ask: `Електроотрицателности: ${a} – ${(en100(a) / 100).toFixed(2).replace('.', ',')}, ${b} – ${(en100(b) / 100).toFixed(2).replace('.', ',')}.`,
      num: d,
      den: 100,
      steps: [
        `$\\Delta\\chi = |${dec(en100(a) / 100)} - ${dec(en100(b) / 100)}| = ${dec(d / 100)}$`,
        d < 40
          ? 'Под около 0,4 – връзката е ковалентна неполярна (или почти неполярна).'
          : d < 170
            ? 'Между около 0,4 и 1,7 – ковалентна полярна.'
            : [a, b].some(s => ['Na', 'K', 'Li', 'Mg', 'Ca'].includes(s))
              ? 'Над около 1,7, при метал и неметал – връзката е йонна.'
              : 'Над около 1,7, но и двата елемента са неметали – връзката е силно полярна ковалентна.',
      ],
    };
  }
  if (kind === 3) {
    const [c, qc] = pick(CAT);
    const [a, qa, poly] = pick(AN);
    const l = (qc * -qa) / gcd(qc, -qa);
    const [n, m] = [l / qc, l / -qa];
    const part = (t: string, k: number, p = false) => (k === 1 ? t : p ? `(${t})_${k}` : `${t}_${k}`);
    const askCation = randInt(0, 1) === 0;
    return {
      tex: `\\mathrm{${c}^{${qc > 1 ? qc : ''}+}} + \\mathrm{${a}^{${-qa > 1 ? -qa : ''}-}}`,
      ask: askCation ? 'Колко катиона има във формулната единица?' : 'Колко аниона има във формулната единица?',
      num: askCation ? n : m,
      den: 1,
      steps: [
        `Най-малкото общо кратно на зарядите ${qc} и ${-qa} е ${l}.`,
        `Катиони: $${l} : ${qc} = ${n}$, аниони: $${l} : ${-qa} = ${m}$`,
        `Формулата е $\\mathrm{${part(c, n)}${part(a, m, poly)}}$.`,
      ],
    };
  }
  const [f, v, lp, why] = pick(MOLS);
  return kind === 4
    ? {
        tex: `\\mathrm{${f}}`,
        ask: 'Колко несподелени електронни двойки има общо в молекулата?',
        num: lp,
        den: 1,
        steps: [`Валентните електрони са ${v}.`, why],
      }
    : {
        tex: `\\mathrm{${f}}`,
        ask: 'Колко валентни електрона има общо в молекулата?',
        num: v,
        den: 1,
        steps: ['Събираме валентните електрони на всички атоми (H – 1, C – 4, N – 5, O – 6, Cl – 7).', `Общо ${v}.`],
      };
};


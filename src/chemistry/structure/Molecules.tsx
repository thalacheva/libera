const domainsStep = (m: Mol) =>
  `Около $\\mathrm{${m.center}}$ има ${m.bonds} ${m.bonds === 1 ? 'свързан атом' : 'свързани атома'} и ${m.lone} ${m.lone === 1 ? 'неподелена двойка' : 'неподелени двойки'}: $${m.bonds} + ${m.lone} = ${m.bonds + m.lone}$ области.`;

const newDrill = (): Drill => {
  const kind = randInt(0, 4);
  const m = pick(MOLS);
  const shape = `Формата е ${SHAPE_NAME[`${m.bonds}-${m.lone}`]}.`;
  if (kind === 0)
    return { tex: m.tex, ask: 'Колко електронни области има около централния атом?', num: m.bonds + m.lone, den: 1, steps: [domainsStep(m), shape] };
  if (kind === 1)
    return { tex: m.tex, ask: 'Колко неподелени електронни двойки има централният атом?', num: m.lone, den: 1, steps: [domainsStep(m), shape] };
  if (kind === 2) {
    const n = pick(MOLS.filter(x => IDEAL[x.bonds + x.lone]));
    const [angle, tex] = IDEAL[n.bonds + n.lone];
    return {
      tex: n.tex,
      ask: 'Какъв е идеалният ъгъл между електронните области около централния атом (в градуси)?',
      num: angle * 10,
      den: 10,
      steps: [domainsStep(n), `При ${n.bonds + n.lone} области идеалният ъгъл е $${tex}^\\circ$.${n.lone ? ' Неподелените двойки го намаляват в реалната молекула.' : ''}`],
    };
  }
  if (kind === 3)
    return {
      tex: m.tex,
      ask: 'Полярна ли е молекулата? Въведи 1 за „да“ и 0 за „не“.',
      num: m.polar ? 1 : 0,
      den: 1,
      steps: [shape, m.polar ? 'Диполите на връзките не се компенсират – молекулата е полярна.' : 'Молекулата е симетрична и диполите на връзките се компенсират – тя е неполярна.'],
    };
  const [[a, ea], [b, eb]] = pick([
    [EN[0], EN[3]],
    [EN[0], EN[2]],
    [EN[1], EN[3]],
    [EN[1], EN[5]],
    [EN[0], EN[4]],
    [EN[0], EN[5]],
    [EN[6], EN[3]],
    [EN[1], EN[0]],
    [EN[0], EN[7]],
    [EN[2], EN[0]],
  ]);
  const d = Math.abs(ea - eb);
  const dec = (v: number) => (v / 100).toFixed(2).replace('.', '{,}');
  return {
    tex: `\\Delta EN(\\mathrm{${a}{-}${b}}) = ?`,
    ask: `Електроотрицателност: ${a} – ${dec(ea).replace('{,}', ',')}, ${b} – ${dec(eb).replace('{,}', ',')}.`,
    num: d,
    den: 100,
    steps: [`$\\Delta EN = |${dec(ea)} - ${dec(eb)}| = ${dec(d)}$`, `Диполът на връзката сочи към ${ea > eb ? a : b} – по-електроотрицателния атом.`],
  };
};


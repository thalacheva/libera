/** Конфигурацията в LaTeX: „[Ne] 3s2 3p5“ → [\\mathrm{Ne}]\\,3s^{2}3p^{5}. */
export const configTex = (config: string) =>
  config
    .split(' ')
    .map(p => (p.startsWith('[') ? `[\\mathrm{${p.slice(1, -1)}}]\\,` : p.replace(/^(\d+[spdf])(\d+)$/, '$1^{$2}')))
    .join('');

/**
 * Ред и колона в таблицата с 18 колони. La и Ac са в група 3, а Ce–Lu и Th–Lr – в два отделни реда
 * отдолу (8 и 9), в колони 4–17.
 */
export function tablePosition(e: Element): { row: number; col: number } {
  if (e.z >= 58 && e.z <= 71) return { row: 8, col: e.z - 54 };
  if (e.z >= 90 && e.z <= 103) return { row: 9, col: e.z - 86 };
  return { row: e.period, col: e.group };
}

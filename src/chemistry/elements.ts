export type Category =
  | 'alkali'
  | 'alkaline-earth'
  | 'transition'
  | 'lanthanide'
  | 'actinide'
  | 'post-transition'
  | 'metalloid'
  | 'nonmetal'
  | 'halogen'
  | 'noble-gas';

export type Element = {
  /** Атомен (пореден) номер */
  z: number;
  symbol: string;
  /** Името на български */
  name: string;
  /** Относителна атомна маса; при radioactive – масово число на най-стабилния изотоп */
  mass: number;
  /** Група 1–18; 0 за Ce–Lu и Th–Lr (редовете под таблицата) */
  group: number;
  period: number;
  category: Category;
  /** Електроотрицателност по Полинг (null – няма стойност) */
  en: number | null;
  /** Първа йонизационна енергия, eV */
  ie: number | null;
  /** Ковалентен радиус, pm */
  radius: number;
  /** Електронна конфигурация, напр. „[Ne] 3s2 3p5“ */
  config: string;
  /** Агрегатно състояние при 25 °C: s, l, g; null – неизвестно */
  state: 's' | 'l' | 'g' | null;
  /** Няма стабилни изотопи и стандартна атомна маса */
  radioactive: boolean;
};


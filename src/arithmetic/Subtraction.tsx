import BunnyGame from './BunnyGame';
import ColumnGame from './ColumnGame';
import CookieGame from './CookieGame';
import CupGame from './CupGame';
import { pick, randInt } from './kidsMath';
import { Challenge, type ChallengeItem, ForParents, GameCard, StoryHero, Tip } from './kit';

const LEVELS = [
  { id: 'to10', label: 'до 10' },
  { id: 'to20', label: 'до 20' },
  { id: 'to100', label: 'до 100' },
  { id: 'to1000', label: 'до 1000' },
] as const;
type Level = (typeof LEVELS)[number]['id'];

function makeTask(level: Level): ChallengeItem {
  let a: number;
  let b: number;
  if (level === 'to10') {
    a = randInt(2, 10);
    b = randInt(1, a - 1);
  } else if (level === 'to20') {
    if (randInt(0, 2) > 0) {
      // през 10: 13 − 5, 16 − 9, …
      a = randInt(11, 18);
      b = randInt(a - 9, 9);
    } else {
      a = randInt(12, 20);
      b = randInt(1, a - 10);
    }
  } else if (level === 'to100') {
    const kind = pick(['bridge', 'tens', 'two'] as const);
    if (kind === 'bridge') {
      a = 10 * randInt(2, 9) + randInt(0, 7);
      b = randInt((a % 10) + 1, 9);
    } else if (kind === 'tens') {
      a = 10 * randInt(3, 10);
      b = 10 * randInt(1, a / 10 - 1);
    } else {
      a = randInt(40, 99);
      b = randInt(11, a - 11);
    }
  } else {
    const kind = pick(['hundreds', 'round'] as const);
    if (kind === 'hundreds') {
      a = 100 * randInt(3, 10);
      b = 100 * randInt(1, a / 100 - 1);
    } else {
      a = 10 * randInt(30, 99);
      b = 10 * randInt(2, Math.min(60, a / 10 - 5));
    }
  }
  return { text: `${a} − ${b}`, answer: a - b };
}


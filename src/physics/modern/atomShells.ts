/** Подслоевете в реда на запълване (правило на Клечковски: по n + l, при равенство – по n). */
export const ORDER: [n: number, l: number][] = [
  [1, 0], [2, 0], [2, 1], [3, 0], [3, 1], [4, 0], [3, 2], [4, 1],
];
export const LETTER = 'spdf';

/** Електронна конфигурация: брой електрони във всеки подслой от ORDER. Хромът и медта са изключения (3d⁵4s¹, 3d¹⁰4s¹). */
export function configuration(Z: number): number[] {
  const out = ORDER.map(() => 0);
  let left = Z;
  ORDER.forEach(([, l], i) => {
    const take = Math.min(left, 2 * (2 * l + 1));
    out[i] = take;
    left -= take;
  });
  if (Z === 24 || Z === 29) {
    out[5] -= 1; // 4s
    out[6] += 1; // 3d
  }
  return out;
}

/** Период и група (1–18) за Z ≤ 36. */
export function position(Z: number): [period: number, group: number] {
  if (Z <= 2) return [1, Z === 1 ? 1 : 18];
  if (Z <= 18) {
    const k = (Z - 2) % 8 || 8; // 1…8 в периода
    const period = Z <= 10 ? 2 : 3;
    return [period, k <= 2 ? k : k + 10];
  }
  return [4, Z - 18];
}

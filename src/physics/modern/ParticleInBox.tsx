            title="Прозрачност на бариера"
            description="Вероятността частицата да премине (прозрачност) при широка бариера ($\kappa d \gg 1$) е приблизително $T \approx e^{-2\kappa d}$, $\kappa = \frac{\sqrt{2m(U - E)}}{\hbar}$. Точната формула съдържа и множител от порядъка на единица, но основното е експонентата: $T$ зависи изключително силно от $d$, от $U - E$ и от масата."

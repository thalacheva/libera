const SUBSHELL_NAMES = ['s', 'p', 'd', 'f'];

/** Електронната конфигурация в LaTeX, по n: 1s^2\,2s^2\,2p^6… */
function confTex(Z: number) {
  const conf = configuration(Z);
  return ORDER.map(([n, l], i) => ({ n, l, k: conf[i] }))
    .filter(s => s.k > 0)
    .sort((a, b) => a.n - b.n || a.l - b.l)
    .map(s => `${s.n}${LETTER[s.l]}^{${s.k}}`)
    .join('\\,');
}

/** Несдвоени електрони по правилото на Хунд. */
function unpaired(Z: number) {
  const conf = configuration(Z);
  return ORDER.reduce((sum, [, l], i) => {
    const cells = 2 * l + 1;
    const k = conf[i];
    return sum + (k <= cells ? k : 2 * cells - k);
  }, 0);
}


const dec = (v: number) =>
  v
    .toLocaleString('en-US', {
      maximumSignificantDigits: 8,
      useGrouping: false,
    })
    .replace('.', '{,}');
const big = (v: number) => (Math.abs(v) >= 10_000 ? String(v).replace(/\B(?=(\d{3})+(?!\d))/g, '\\,') : dec(v));

const newDrill = (): Drill => {
  const kind = randInt(0, 4);
  if (kind === 0) {
    // Статична обезпеченост
    const [name, unit, R, P] = pick<[string, string, number, number]>([
      ['мед', 'млн. t', 980, 23],
      ['нефт', 'млрд. барела', 1700, 32],
      ['никел', 'млн. t', 130, 3.7],
      ['цинк', 'млн. t', 220, 12],
      ['злато', 'хил. t', 64, 3.3],
    ]);
    const rp = R / P;
    return {
      tex: `\\text{${name}}:\\ R = ${big(R)}\\ \\text{${unit}},\\ P = ${dec(P)}\\ \\text{${unit} годишно}`,
      ask: 'За колко години стигат запасите при днешния добив (до цяло)?',
      num: Math.round(rp),
      den: 1,
      steps: [`$\\frac{R}{P} = \\frac{${big(R)}}{${dec(P)}} \\approx ${Math.round(rp)}$ години`],
    };
  }
  if (kind === 1) {
    // Годишна енергия по коефициента на използване
    const [name, Pw, cf] = pick<[string, number, number]>([
      ['соларен парк', 50, 0.15],
      ['соларен парк', 120, 0.14],
      ['вятърен парк', 60, 0.25],
      ['вятърен парк', 150, 0.3],
      ['ВЕЦ', 80, 0.35],
      ['атомен реактор', 1000, 0.9],
    ]);
    const E = (Pw * 8760 * cf) / 1000;
    return {
      tex: `\\text{${name}}:\\ P = ${big(Pw)}\\ \\mathrm{MW},\\ \\text{КИ} = ${dec(cf * 100)}\\%`,
      ask: 'Колко GWh произвежда за една година (до цяло)?',
      num: Math.round(E),
      den: 1,
      steps: [`$E = P \\cdot 8760\\ \\mathrm{h} \\cdot \\text{КИ} = ${big(Pw)} \\cdot 8760 \\cdot ${dec(cf)} \\approx ${big(Math.round(E * 1000))}\\ \\mathrm{MWh} \\approx ${Math.round(E)}$ GWh`],
    };
  }
  if (kind === 2) {
    // Мощност на вятъра ∝ v³
    const v1 = pick([4, 5, 6]);
    const v2 = v1 + pick([1, 2, 3, 4]);
    const ratio = (v2 / v1) ** 3;
    return {
      tex: `v_1 = ${v1}\\ \\mathrm{m/s},\\quad v_2 = ${v2}\\ \\mathrm{m/s}`,
      ask: 'Колко пъти по-голяма е мощността на вятъра при v₂ (до десети)?',
      num: Math.round(ratio * 10),
      den: 10,
      steps: [`$\\frac{P_2}{P_1} = \\left(\\frac{v_2}{v_1}\\right)^3 = \\left(\\frac{${v2}}{${v1}}\\right)^3 \\approx ${dec(Math.round(ratio * 10) / 10)}$`],
    };
  }
  if (kind === 3) {
    // Тон нефтен еквивалент
    const t = pick([2, 5, 10, 20, 50]);
    const gj = t * 41.868;
    return {
      tex: `${t}\\ \\text{t н.е.}`,
      ask: 'Колко GJ са (до цяло)? 1 t нефтен еквивалент = 41,868 GJ.',
      num: Math.round(gj),
      den: 1,
      steps: [`$${t} \\cdot 41{,}868 \\approx ${Math.round(gj)}$ GJ`],
    };
  }
  // Изчерпване при растящ добив
  const rp = pick([30, 40, 50, 60, 100]);
  const r = pick([1, 2, 3, 5]);
  const T = Math.log(1 + (r / 100) * rp) / Math.log(1 + r / 100);
  return {
    tex: `R/P = ${rp}\\ \\text{години},\\ \\text{добивът расте с}\\ ${r}\\%\\ \\text{годишно}`,
    ask: 'След колко години запасите ще свършат (до цяло)?',
    num: Math.round(T),
    den: 1,
    steps: [
      `Сборът от добивите за $T$ години е $\\frac{(1 + r)^T - 1}{r}$ днешни годишни добива.`,
      `$T = \\frac{\\ln(1 + r \\cdot R/P)}{\\ln(1 + r)} = \\frac{\\ln(1 + ${dec(r / 100)} \\cdot ${rp})}{\\ln ${dec(1 + r / 100)}} \\approx ${Math.round(T)}$ години`,
    ],
  };
};


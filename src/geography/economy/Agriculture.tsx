const dec = (v: number) =>
  v
    .toLocaleString('en-US', {
      maximumSignificantDigits: 8,
      useGrouping: false,
    })
    .replace('.', '{,}');
const big = (v: number) => (Math.abs(v) >= 10_000 ? String(v).replace(/\B(?=(\d{3})+(?!\d))/g, '\\,') : dec(v));

const newDrill = (): Drill => {
  const kind = randInt(0, 4);
  if (kind === 0) {
    // Реколта = площ · добив
    const S = pick([80, 120, 250, 400, 600, 1500]);
    const y = pick([2.5, 3, 4.5, 5, 5.5, 6, 7.5]);
    return {
      tex: `S = ${big(S)}\\ \\mathrm{ha},\\ y = ${dec(y)}\\ \\mathrm{t/ha}`,
      ask: 'Колко тона е реколтата?',
      num: Math.round(S * y * 10),
      den: 10,
      steps: [`$P = S \\cdot y = ${big(S)} \\cdot ${dec(y)} = ${big(Math.round(S * y * 10) / 10)}$ t`],
    };
  }
  if (kind === 1) {
    // Поземлена рента
    const Y = pick([2, 4, 5, 10, 20]);
    const m = pick([50, 80, 100, 120]);
    const f = pick([1, 2, 3, 5]);
    const d = pick([5, 10, 15, 20]);
    const R = Y * m - Y * f * d;
    return {
      tex: `Y = ${Y}\\ \\mathrm{t/ha},\\ p - c = ${m}\\ \\text{€/t},\\ f = ${f}\\ \\text{€/(t·km)},\\ d = ${d}\\ \\mathrm{km}`,
      ask: 'Колко е поземлената рента (€/ha)? Ако е отрицателна, въведи я със знак минус.',
      num: R,
      den: 1,
      steps: [`$R = Y(p - c) - Y f d = ${Y} \\cdot ${m} - ${Y} \\cdot ${f} \\cdot ${d} = ${Y * m} - ${Y * f * d} = ${R}$ €/ha`],
    };
  }
  if (kind === 2) {
    // Граница на отглеждането
    const m = pick([60, 80, 100, 120, 150, 200]);
    const f = pick([1, 2, 4, 5]);
    return {
      tex: `p - c = ${m}\\ \\text{€/t},\\ f = ${f}\\ \\text{€/(t·km)}`,
      ask: 'До колко километра от пазара се изплаща да се отглежда продуктът?',
      num: m / f,
      den: 1,
      steps: [`Рентата става нула при $d = \\frac{p - c}{f} = \\frac{${m}}{${f}} = ${dec(m / f)}$ km. Добивът $Y$ се съкращава.`],
    };
  }
  if (kind === 3) {
    // Воден отпечатък
    const [name, L] = pick<[string, number]>([
      ['говеждо месо', 15_400],
      ['пилешко месо', 4_300],
      ['пшеница', 1_800],
      ['ориз', 2_500],
      ['картофи', 290],
    ]);
    const g = pick([200, 250, 500, 1000, 1500]);
    const v = (L * g) / 1000;
    return {
      tex: `\\text{${name}}:\\ ${big(L)}\\ \\text{l/kg},\\ m = ${g}\\ \\mathrm{g}`,
      ask: 'Колко литра вода стоят зад тази храна?',
      num: Math.round(v),
      den: 1,
      steps: [`$${big(L)} \\cdot ${dec(g / 1000)} = ${big(Math.round(v))}$ l`],
    };
  }
  // Напояване: 1 mm на 1 ha = 10 m³
  const mm = pick([20, 30, 50, 80, 100, 150]);
  const S = pick([2, 5, 10, 40]);
  return {
    tex: `${mm}\\ \\mathrm{mm}\\ \\text{вода върху}\\ ${S}\\ \\mathrm{ha}`,
    ask: 'Колко кубични метра вода са нужни?',
    num: mm * S * 10,
    den: 1,
    steps: [`$1\\ \\mathrm{mm}$ върху $1\\ \\mathrm{ha} = 0{,}001\\ \\mathrm{m} \\cdot 10\\,000\\ \\mathrm{m^2} = 10\\ \\mathrm{m^3}$.`, `$${mm} \\cdot ${S} \\cdot 10 = ${big(mm * S * 10)}\\ \\mathrm{m^3}$`],
  };
};


const dec = (v: number) =>
  v
    .toLocaleString('en-US', {
      maximumSignificantDigits: 8,
      useGrouping: false,
    })
    .replace('.', '{,}');
const big = (v: number) => (Math.abs(v) >= 10_000 ? String(v).replace(/\B(?=(\d{3})+(?!\d))/g, '\\,') : dec(v));
const r2 = (v: number) => Math.round(v * 100) / 100;

const newDrill = (): Drill => {
  const kind = randInt(0, 5);
  if (kind === 0) {
    // Индекс β
    const v = randInt(5, 14);
    const e = randInt(v - 1, 2 * v);
    return {
      tex: `v = ${v}\\ \\text{възела},\\ e = ${e}\\ \\text{връзки}`,
      ask: 'Колко е индексът β на свързаност (до стотни)?',
      num: Math.round((e / v) * 100),
      den: 100,
      steps: [`$\\beta = \\frac{e}{v} = \\frac{${e}}{${v}} \\approx ${dec(r2(e / v))}$`],
    };
  }
  if (kind === 1) {
    // Индекс γ
    const v = randInt(5, 12);
    const max = 3 * (v - 2);
    const e = randInt(v - 1, max);
    return {
      tex: `v = ${v}\\ \\text{възела},\\ e = ${e}\\ \\text{връзки (равнинна мрежа)}`,
      ask: 'Колко е индексът γ (до стотни)?',
      num: Math.round((e / max) * 100),
      den: 100,
      steps: [`Най-много връзки в равнинна мрежа: $3(v - 2) = 3 \\cdot ${v - 2} = ${max}$.`, `$\\gamma = \\frac{${e}}{${max}} \\approx ${dec(r2(e / max))}$`],
    };
  }
  if (kind === 2) {
    // Въглероден диоксид от превоза
    const [mode, f] = pick<[string, number]>([
      ['камион', 80],
      ['влак', 25],
      ['кораб', 10],
      ['самолет', 600],
    ]);
    const m = pick([5, 10, 20, 25, 40]);
    const d = pick([200, 300, 500, 800, 1200, 2000]);
    const kg = (m * d * f) / 1000;
    return {
      tex: `${m}\\ \\mathrm{t},\\ ${big(d)}\\ \\mathrm{km},\\ \\text{${mode}}:\\ ${f}\\ \\mathrm{g\\,CO_2/(t \\cdot km)}`,
      ask: 'Колко килограма CO₂ се отделят при превоза?',
      num: Math.round(kg),
      den: 1,
      steps: [`Товарооборот: $${m} \\cdot ${big(d)} = ${big(m * d)}$ t·km.`, `$${big(m * d)} \\cdot ${f}\\ \\mathrm{g} = ${big(m * d * f)}\\ \\mathrm{g} = ${big(kg)}$ kg`],
    };
  }
  if (kind === 3) {
    // Търговски баланс и покритие
    const ex = pick([8, 12, 15, 24, 36, 45]);
    const im = pick([10, 14, 16, 20, 30, 50]);
    const cov = (ex / im) * 100;
    return {
      tex: `\\text{износ}\\ ${ex}\\ \\text{млрд. €},\\ \\text{внос}\\ ${im}\\ \\text{млрд. €}`,
      ask: 'Какъв е коефициентът на покритие на вноса с износ (%, до десети)?',
      num: Math.round(cov * 10),
      den: 10,
      steps: [`Баланс: $${ex} - ${im} = ${ex - im}$ млрд. € – ${ex >= im ? 'излишък' : 'дефицит'}.`, `Покритие: $\\frac{${ex}}{${im}} \\cdot 100 \\approx ${dec(Math.round(cov * 10) / 10)}\\%$`],
    };
  }
  if (kind === 4) {
    // Алтернативна цена
    const a = pick([2, 3, 4, 5, 6, 8]);
    const b = pick([2, 3, 4, 5, 10]);
    return {
      tex: `1\\ \\text{вино} = ${a}\\ \\text{часа},\\ 1\\ \\text{плат} = ${b}\\ \\text{часа}`,
      ask: 'Колко единици плат струва една единица вино (алтернативна цена, до стотни)?',
      num: Math.round((a / b) * 100),
      den: 100,
      steps: [`С часовете за 1 вино могат да се направят $\\frac{${a}}{${b}} \\approx ${dec(r2(a / b))}$ плат.`],
    };
  }
  // Време за плаване
  const d = pick([4000, 8000, 12_000, 19_500, 25_900]);
  const kn = pick([12, 14, 16, 20]);
  const day = kn * 1.852 * 24;
  return {
    tex: `${big(d)}\\ \\mathrm{km}\\ \\text{при}\\ ${kn}\\ \\text{възела}`,
    ask: 'За колко денонощия корабът изминава пътя (до десети)?',
    num: Math.round((d / day) * 10),
    den: 10,
    steps: [`$1$ възел $= 1{,}852$ km/h: $${kn} \\cdot 1{,}852 \\cdot 24 \\approx ${dec(Math.round(day))}$ km на денонощие.`, `$\\frac{${big(d)}}{${dec(Math.round(day * 10) / 10)}} \\approx ${dec(Math.round((d / day) * 10) / 10)}$ денонощия`],
  };
};


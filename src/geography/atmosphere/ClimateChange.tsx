const dec = (v: number) => v.toLocaleString('en-US', { maximumSignificantDigits: 8, useGrouping: false }).replace('.', '{,}');
const r2 = (v: number) => Math.round(v * 100) / 100;

const newDrill = (): Drill => {
  const kind = randInt(0, 5);
  if (kind === 0) {
    // Радиационно въздействие на CO₂
    const c = pick([350, 420, 560, 700, 840, 1120]);
    const f = r2(5.35 * Math.log(c / 280));
    return {
      tex: `C_0 = 280\\ \\mathrm{ppm},\\ C = ${c}\\ \\mathrm{ppm}`,
      ask: 'Колко е радиационното въздействие ΔF в W/m² (закръгли до стотни)?',
      num: Math.round(f * 100),
      den: 100,
      steps: [`$\\Delta F = 5{,}35 \\ln\\frac{${c}}{280} = 5{,}35 \\cdot ${dec(r2(Math.log(c / 280) * 1000) / 1000)} \\approx ${dec(f)}\\ \\mathrm{W/m^2}$`],
    };
  }
  if (kind === 1) {
    // Обратни връзки
    const t0 = pick([1, 1.2]);
    const f = pick([0.25, 0.4, 0.5, 0.6, 0.7]);
    const t = r2(t0 / (1 - f));
    return {
      tex: `\\Delta T_0 = ${dec(t0)}\\ ^\\circ\\mathrm{C},\\ f = ${dec(f)}`,
      ask: 'Колко е затоплянето с обратните връзки в °C (закръгли до стотни)?',
      num: Math.round(t * 100),
      den: 100,
      steps: [`$\\Delta T = \\frac{\\Delta T_0}{1 - f} = \\frac{${dec(t0)}}{${dec(r2(1 - f))}} \\approx ${dec(t)}\\ ^\\circ\\mathrm{C}$`],
    };
  }
  if (kind === 2) {
    // Колко CO₂ остава във въздуха
    const e = pick([30, 35, 39, 40, 42]);
    const ppm = r2((e * 0.45) / 7.8);
    return {
      tex: `E = ${e}\\ \\mathrm{Gt\\,CO_2/год.}`,
      ask: 'Във въздуха остават 45%, а 1 ppm = 7,8 Gt CO₂. С колко ppm нараства CO₂ за година (закръгли до стотни)?',
      num: Math.round(ppm * 100),
      den: 100,
      steps: [`Във въздуха остават $0{,}45 \\cdot ${e} = ${dec(r2(0.45 * e))}\\ \\mathrm{Gt\\,CO_2}$.`, `$\\frac{${dec(r2(0.45 * e))}}{7{,}8} \\approx ${dec(ppm)}\\ \\mathrm{ppm}$`],
    };
  }
  if (kind === 3) {
    // Въглероден бюджет
    const b = pick([250, 400, 500, 1150]);
    const e = pick([25, 36, 40]);
    const y = Math.round((b / e) * 10) / 10;
    return {
      tex: `B = ${b}\\ \\mathrm{Gt},\\ E = ${e}\\ \\mathrm{Gt/год.}`,
      ask: 'B е бюджетът, а E – годишните емисии на CO₂. За колко години се изчерпва бюджетът (закръгли до десети)?',
      num: Math.round(y * 10),
      den: 10,
      steps: [`$t = \\frac{${b}}{${e}} \\approx ${dec(y)}$ години`],
    };
  }
  if (kind === 4) {
    // Затопляне от сумарните емисии
    const cum = pick([1000, 1500, 2000, 2400, 3000, 4000]);
    const t = r2((cum * 0.45) / 1000);
    return {
      tex: `E_{\\text{сумарно}} = ${cum}\\ \\mathrm{Gt\\,CO_2}`,
      ask: 'При 0,45 °C на 1000 Gt CO₂ – с колко °C се затопля Земята от този CO₂?',
      num: Math.round(t * 100),
      den: 100,
      steps: [`$\\Delta T = 0{,}45 \\cdot \\frac{${cum}}{1000} = ${dec(t)}\\ ^\\circ\\mathrm{C}$`],
    };
  }
  // Покачване на морското равнище
  const rate = pick([1.5, 3, 3.7, 4.5]);
  const years = pick([20, 50, 80, 100]);
  const cm = r2((rate * years) / 10);
  return {
    tex: `${dec(rate)}\\ \\mathrm{mm/год.},\\ ${years}\\ \\text{години}`,
    ask: 'С колко сантиметра се покачва морското равнище?',
    num: Math.round(cm * 100),
    den: 100,
    steps: [`$${dec(rate)} \\cdot ${years} = ${dec(r2(rate * years))}\\ \\mathrm{mm} = ${dec(cm)}\\ \\mathrm{cm}$`],
  };
};


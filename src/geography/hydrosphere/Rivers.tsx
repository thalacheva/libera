const dec = (v: number) =>
  v
    .toLocaleString('en-US', {
      maximumSignificantDigits: 8,
      useGrouping: false,
    })
    .replace('.', '{,}');
const big = (v: number) => (v >= 10_000 ? String(v).replace(/\B(?=(\d{3})+(?!\d))/g, '\\,') : dec(v));
const round = (v: number, d: number) => Math.round(v * 10 ** d) / 10 ** d;


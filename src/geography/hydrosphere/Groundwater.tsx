          <p className={text}>
            Подземната вода тече от по-високото към по-ниското водно ниво, но много бавно – обикновено от сантиметри до метри на ден. Колко вода протича, казва
            законът, който Дарси открива с пясъчните си тръби.
          </p>
          <Theorem
            title="Законът на Дарси"
            description="$Q = K\,A\,\dfrac{\Delta h}{L}$: дебитът $Q$ (m³/s) е пропорционален на коефициента на филтрация $K$, на площта на сечението $A$ и на наклона на водното ниво $i = \Delta h / L$. Водата минава само през порите, затова **действителната** ѝ скорост е $v = \dfrac{K\,i}{n_e}$, където $n_e$ е ефективната порестост."

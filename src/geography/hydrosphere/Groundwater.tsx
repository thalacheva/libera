            type="definition"
            title="Артезиански води"
            description="Напорни подземни води, които в кладенеца се издигат над горната граница на пласта; ако пиезометричното им ниво е над терена, бликат сами. Името идва от областта Артоа (лат. Artesium) в Северна Франция, където такива кладенци се копаят от Средновековието."

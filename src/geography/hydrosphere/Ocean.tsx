const big = (v: number) => (v >= 10_000 ? String(v).replace(/\B(?=(\d{3})+(?!\d))/g, '\\,') : dec(v));
const hm = (min: number) => `${Math.floor(min / 60) % 24}:${String(Math.round(min % 60)).padStart(2, '0')}`;


const dec = (v: number) => v.toLocaleString('en-US', { maximumSignificantDigits: 8, useGrouping: false }).replace('.', '{,}');
const big = (v: number) => (v >= 10_000 ? String(v).replace(/\B(?=(\d{3})+(?!\d))/g, '\\,') : dec(v));

const newDrill = (): Drill => {
  const kind = randInt(0, 5);
  if (kind === 0) {
    // Скорост на ерозията
    const rate = pick([0.05, 0.1, 0.2, 0.5]);
    const years = pick([10_000, 100_000, 1_000_000]);
    const m = (rate * years) / 1000;
    return {
      tex: `${dec(rate)}\\ \\mathrm{mm/год.},\\ t = ${big(years)}\\ \\text{год.}`,
      ask: 'С колко метра се снижава повърхността?',
      num: Math.round(m * 100),
      den: 100,
      steps: [`$${dec(rate)} \\cdot ${big(years)} = ${big(rate * years)}\\ \\mathrm{mm} = ${dec(m)}\\ \\mathrm{m}$`],
    };
  }
  if (kind === 1) {
    // Замръзване
    const v = pick([50, 100, 200, 300, 500]);
    return {
      tex: `V_{\\text{вода}} = ${v}\\ \\mathrm{cm^3}`,
      ask: 'Колко cm³ лед се получава (водата се разширява с 9%)?',
      num: Math.round(v * 109),
      den: 100,
      steps: [`$V_{\\text{лед}} = ${v} \\cdot 1{,}09 = ${dec(v * 1.09)}\\ \\mathrm{cm^3}$`],
    };
  }
  if (kind === 2) {
    // Коефициент на извитост
    const [L, D] = pick<[number, number]>([
      [30, 20],
      [42, 24],
      [25, 20],
      [36, 16],
      [18, 12],
      [27, 12],
    ]);
    return {
      tex: `L_{\\text{корито}} = ${L}\\ \\mathrm{km},\\ L_{\\text{долина}} = ${D}\\ \\mathrm{km}`,
      ask: 'Колко е коефициентът на извитост?',
      num: L,
      den: D,
      steps: [`$k = \\frac{${L}}{${D}} = ${dec(L / D)}$${L / D >= 1.5 ? ' – реката меандрира' : ''}`],
    };
  }
  if (kind === 3) {
    // Скорост на ледник
    const v = pick([0.1, 0.2, 0.4, 0.5, 1, 2]);
    return {
      tex: `v = ${dec(v)}\\ \\mathrm{m/ден}`,
      ask: 'Колко метра изминава ледникът за година (365 дни)?',
      num: Math.round(v * 365 * 10),
      den: 10,
      steps: [`$${dec(v)} \\cdot 365 = ${dec(v * 365)}\\ \\mathrm{m}$`],
    };
  }
  if (kind === 4) {
    // Карстова денудация
    const R = pick([200, 300, 400, 500, 600, 800]);
    const c = pick([100, 150, 200, 250]);
    const g = (R / 1000) * c;
    return {
      tex: `\\text{отток } ${R}\\ \\mathrm{mm/год.},\\ ${c}\\ \\mathrm{mg/L}\\ \\mathrm{CaCO_3}`,
      ask: 'Колко грама варовик на m² изнася водата за година?',
      num: Math.round(g * 10),
      den: 10,
      steps: [`$${R}\\ \\mathrm{mm} = ${dec(R / 1000)}\\ \\mathrm{m}$ вода на $1\\ \\mathrm{m^2}$ – това са $${R}$ литра.`, `$${R} \\cdot ${c}\\ \\mathrm{mg} = ${big(R * c)}\\ \\mathrm{mg} = ${dec(g)}\\ \\mathrm{g}$`],
    };
  }
  // Растеж на сталактит
  const rate = pick([0.1, 0.2, 0.5, 1]);
  const years = pick([100, 500, 1000, 2000]);
  return {
    tex: `${dec(rate)}\\ \\mathrm{mm/год.},\\ ${years}\\ \\text{год.}`,
    ask: 'С колко сантиметра нараства сталактитът?',
    num: Math.round(rate * years),
    den: 10,
    steps: [`$${dec(rate)} \\cdot ${years} = ${dec(rate * years)}\\ \\mathrm{mm} = ${dec((rate * years) / 10)}\\ \\mathrm{cm}$`],
  };
};


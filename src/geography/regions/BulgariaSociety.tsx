const newDrill = (): Drill => {
  const kind = randInt(0, 4);
  const [name, p11, p21, area] = pick(OBL);
  if (kind === 0) {
    // гъстота
    const d = Math.round((p21 / area) * 10) / 10;
    return {
      tex: `P = ${big(p21)},\\quad S = ${big(area)}\\ \\text{km}^2`,
      ask: `Област ${name}, 2021 г. Колко е гъстотата на населението (души/km², до десети)?`,
      num: Math.round(d * 10),
      den: 10,
      steps: [`$\\frac{${big(p21)}}{${big(area)}} \\approx ${dec(d)}$ души/km²`],
    };
  }
  if (kind === 1) {
    // промяна между преброяванията
    const ch = Math.round(((p21 - p11) / p11) * 1000) / 10;
    return {
      tex: `P_{2011} = ${big(p11)},\\quad P_{2021} = ${big(p21)}`,
      ask: `Област ${name}. С колко процента се е променило населението (до десети, със знак)?`,
      num: Math.round(ch * 10),
      den: 10,
      steps: [`$\\frac{${big(p21)} - ${big(p11)}}{${big(p11)}} \\cdot 100 \\approx ${dec(ch)}\\%$`],
    };
  }
  if (kind === 2) {
    // естествен прираст в брой хора
    const P = pick([70_000, 90_000, 120_000, 200_000, 400_000]);
    const k = pick([-17, -14, -12, -9, -5, -2]);
    const n = (P * k) / 1000;
    return {
      tex: `P = ${big(P)},\\quad k = ${k}\\ \\text{‰}`,
      ask: 'Естественият прираст на областта е k промила. С колко души се променя населението ѝ за година само от раждания и смъртни случаи?',
      num: n,
      den: 1,
      steps: [`$${big(P)} \\cdot \\frac{${k}}{1000} = ${big(n)}$ души`],
    };
  }
  if (kind === 3) {
    // дял на областта
    const share = Math.round((p21 / 6_519_789) * 1000) / 10;
    return {
      tex: `P_{\\text{обл}} = ${big(p21)},\\quad P_{\\text{БГ}} = 6\\,519\\,789`,
      ask: `Каква част от населението на България живее в област ${name} (в %, до десети)?`,
      num: Math.round(share * 10),
      den: 10,
      steps: [`$\\frac{${big(p21)}}{6\\,519\\,789} \\cdot 100 \\approx ${dec(share)}\\%$`],
    };
  }
  // заетост на леглата
  const beds = pick([100, 150, 200, 400]);
  const days = pick([30, 31]);
  const occ = pick([40, 50, 60, 75, 90]);
  const nights = (beds * days * occ) / 100;
  return {
    tex: `${beds}\\ \\text{легла},\\ ${days}\\ \\text{дни},\\ ${big(nights)}\\ \\text{нощувки}`,
    ask: 'Каква е заетостта на леглата в хотела през месеца (в %)?',
    num: occ,
    den: 1,
    steps: [`$\\frac{${big(nights)}}{${beds} \\cdot ${days}} \\cdot 100 = ${occ}\\%$`],
  };
};


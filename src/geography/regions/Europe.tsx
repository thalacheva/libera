const dec = (v: number) =>
  v
    .toLocaleString('en-US', {
      maximumSignificantDigits: 8,
      useGrouping: false,
    })
    .replace('.', '{,}');
const big = (v: number) => (Math.abs(v) >= 10_000 ? String(v).replace(/\B(?=(\d{3})+(?!\d))/g, '\\,') : dec(v));
const r1 = (v: number) => Math.round(v * 10) / 10;
const r2 = (v: number) => Math.round(v * 100) / 100;

const RATE = 1.95583;

const newDrill = (): Drill => {
  const kind = randInt(0, 5);
  if (kind === 0) {
    // Левове в евро
    const lv = pick([10, 25, 50, 120, 350, 980, 1500, 2400]);
    const eur = lv / RATE;
    return {
      tex: `${big(lv)}\\ \\text{лв.},\\quad 1\\ € = 1{,}95583\\ \\text{лв.}`,
      ask: 'Колко евро са (до цент)?',
      num: Math.round(eur * 100),
      den: 100,
      steps: [`$\\frac{${big(lv)}}{1{,}95583} \\approx ${dec(r2(eur))}$ €`],
    };
  }
  if (kind === 1) {
    // Жители на едно място в Европейския парламент
    const [name, p, m] = pick<[string, number, number]>([
      ['Германия', 83.58, 96],
      ['Франция', 68.88, 81],
      ['Полша', 36.5, 53],
      ['България', 6.44, 17],
      ['Хърватия', 3.87, 12],
      ['Естония', 1.37, 7],
      ['Малта', 0.57, 6],
    ]);
    const k = (p * 1000) / m;
    return {
      tex: `\\text{${name}}:\\ ${dec(p)}\\ \\text{млн. жители},\\ ${m}\\ \\text{места в ЕП}`,
      ask: 'Колко хиляди жители се падат на едно място (до хиляда)?',
      num: Math.round(k),
      den: 1,
      steps: [`$\\frac{${dec(p)}\\ \\text{млн.}}{${m}} = \\frac{${big(Math.round(p * 1000))}\\ \\text{хил.}}{${m}} \\approx ${Math.round(k)}$ хил.`],
    };
  }
  if (kind === 2) {
    // Индекс на БВП на човек по ППС
    const eu = pick([36_000, 37_000, 38_000, 40_000]);
    const x = pick([14_400, 16_200, 18_300, 27_500, 31_000, 44_800, 52_000]);
    const idx = (x / eu) * 100;
    return {
      tex: `\\text{регион: } ${big(x)}\\ \\text{ППС на човек},\\ \\text{ЕС: } ${big(eu)}`,
      ask: 'Колко процента от средното за ЕС е регионът (до десети)?',
      num: Math.round(idx * 10),
      den: 10,
      steps: [`$\\frac{${big(x)}}{${big(eu)}} \\cdot 100 \\approx ${dec(r1(idx))}\\%$ – ${idx < 75 ? 'по-слабо развит регион (под 75%)' : idx < 100 ? 'регион в преход (75–100%)' : 'по-развит регион (над 100%)'}.`],
    };
  }
  if (kind === 3) {
    // Време за догонване
    const i0 = pick([40, 45, 50, 60, 66]);
    const target = pick([75, 100]);
    const g = pick([3, 3.5, 4, 5]);
    const ge = pick([1, 1.5, 2]);
    const t = Math.log(target / i0) / Math.log((1 + g / 100) / (1 + ge / 100));
    return {
      tex: `I_0 = ${i0}\\%,\\ g = ${dec(g)}\\%,\\ g_{ЕС} = ${dec(ge)}\\%`,
      ask: `След колко години регионът ще стигне ${target}% от средното за ЕС (до десети)?`,
      num: Math.round(t * 10),
      den: 10,
      steps: [
        `Всяка година нивото се умножава по $\\frac{1 + ${dec(g / 100)}}{1 + ${dec(ge / 100)}} \\approx ${dec(Math.round(((1 + g / 100) / (1 + ge / 100)) * 10000) / 10000)}$.`,
        `$t = \\frac{\\ln(${target}/${i0})}{\\ln ${dec(Math.round(((1 + g / 100) / (1 + ge / 100)) * 10000) / 10000)}} \\approx ${dec(r1(t))}$ години`,
      ],
    };
  }
  if (kind === 4) {
    // Маастрихтски критерий за дефицита
    const gdp = pick([80, 104, 120, 250, 400]);
    const d = pick([1.5, 2.4, 3.3, 4.8, 7.2, 9]);
    const pct = (d / gdp) * 100;
    return {
      tex: `\\text{БВП } ${gdp}\\ \\text{млрд. €},\\ \\text{бюджетен дефицит } ${dec(d)}\\ \\text{млрд. €}`,
      ask: 'Колко процента от БВП е дефицитът (до стотни)?',
      num: Math.round(pct * 100),
      den: 100,
      steps: [`$\\frac{${dec(d)}}{${gdp}} \\cdot 100 \\approx ${dec(r2(pct))}\\%$ – ${pct <= 3 ? 'в границата от 3%' : 'над границата от 3%'}.`],
    };
  }
  // Население „за“ в Съвета
  const groups: [string, number][] = [
    ['Германия', 18.5],
    ['Франция', 15.3],
    ['Италия', 13.1],
    ['Испания', 10.9],
    ['Полша', 8.1],
    ['Румъния', 4.2],
    ['Нидерландия', 4.0],
  ];
  const k = randInt(2, 4);
  const start = randInt(0, groups.length - k);
  const against = groups.slice(start, start + k);
  const sum = against.reduce((s, [, v]) => s + v, 0);
  return {
    tex: `\\text{против: } ${against.map(([n, v]) => `\\text{${n}}\\ (${dec(v)}\\%)`).join(',\\ ')}`,
    ask: 'Останалите държави са „за“. Колко процента от населението на ЕС са „за“ (до десети)?',
    num: Math.round((100 - sum) * 10),
    den: 10,
    steps: [
      `Против: $${against.map(([, v]) => dec(v)).join(' + ')} = ${dec(r1(sum))}\\%$.`,
      `За: $100 - ${dec(r1(sum))} = ${dec(r1(100 - sum))}\\%$ – ${100 - sum >= 65 ? 'над 65%' : k < 4 ? 'под 65%, но против са под 4 държави, така че решението се смята за прието' : 'под 65% – блокиращо малцинство'}.`,
    ],
  };
};


const dec = (v: number) =>
  v
    .toLocaleString('en-US', {
      maximumSignificantDigits: 8,
      useGrouping: false,
    })
    .replace('.', '{,}');
const big = (v: number) => (Math.abs(v) >= 10_000 ? String(v).replace(/\B(?=(\d{3})+(?!\d))/g, '\\,') : dec(v));
const r3 = (v: number) => Math.round(v * 1000) / 1000;

const newDrill = (): Drill => {
  const kind = randInt(0, 5);
  if (kind === 0) {
    // ИЧР от трите индекса
    const a = pick([0.6, 0.7, 0.8, 0.85, 0.9, 0.95]);
    const b = pick([0.5, 0.6, 0.7, 0.8, 0.9]);
    const c = pick([0.55, 0.65, 0.75, 0.85, 0.95]);
    const h = Math.cbrt(a * b * c);
    return {
      tex: `I_{\\text{здраве}} = ${dec(a)},\\ I_{\\text{обр.}} = ${dec(b)},\\ I_{\\text{доход}} = ${dec(c)}`,
      ask: 'Колко е ИЧР (до хилядни)?',
      num: Math.round(h * 1000),
      den: 1000,
      steps: [`Произведение: $${dec(a)} \\cdot ${dec(b)} \\cdot ${dec(c)} = ${dec(r3(a * b * c))}$`, `$\\text{ИЧР} = \\sqrt[3]{${dec(r3(a * b * c))}} \\approx ${dec(r3(h))}$`],
    };
  }
  if (kind === 1) {
    // Индекс на здравето
    const le = randInt(55, 85);
    const i = (le - 20) / 65;
    return {
      tex: `e_0 = ${le}\\ \\text{години}`,
      ask: 'Колко е индексът на здравето (до хилядни)?',
      num: Math.round(i * 1000),
      den: 1000,
      steps: [`$I = \\frac{e_0 - 20}{85 - 20} = \\frac{${le - 20}}{65} \\approx ${dec(r3(i))}$`],
    };
  }
  if (kind === 2) {
    // Индекс на дохода
    const g = pick([1000, 2000, 5000, 10_000, 20_000, 30_000, 50_000]);
    const i = Math.log(g / 100) / Math.log(750);
    return {
      tex: `\\text{БНД на човек} = ${big(g)}\\ \\$\\ \\text{(ППС)}`,
      ask: 'Колко е индексът на дохода (до хилядни)?',
      num: Math.round(i * 1000),
      den: 1000,
      steps: [`$I = \\frac{\\ln ${big(g)} - \\ln 100}{\\ln 75\\,000 - \\ln 100} = \\frac{\\ln ${g / 100}}{\\ln 750}$`, `$= \\frac{${dec(Math.round(Math.log(g / 100) * 1000) / 1000)}}{6{,}620} \\approx ${dec(r3(i))}$`],
    };
  }
  if (kind === 3) {
    // Индекс на компактност
    const s = pick([10_000, 30_000, 50_000, 100_000, 200_000, 300_000]);
    const p = pick([800, 1000, 1500, 2000, 3000, 5000]);
    const c = (4 * Math.PI * s) / (p * p);
    if (c > 1) return newDrill();
    return {
      tex: `S = ${big(s)}\\ \\mathrm{km^2},\\ P = ${big(p)}\\ \\mathrm{km}`,
      ask: 'Колко е индексът на компактност 4πS/P² (до хилядни)?',
      num: Math.round(c * 1000),
      den: 1000,
      steps: [`$\\frac{4\\pi \\cdot ${big(s)}}{${big(p)}^2} = \\frac{${big(Math.round(4 * Math.PI * s))}}{${big(p * p)}} \\approx ${dec(r3(c))}$`],
    };
  }
  if (kind === 4) {
    // Морски мили в километри
    const nm = pick([3, 6, 12, 24, 50, 100, 200, 350]);
    return {
      tex: `${nm}\\ \\text{морски мили}`,
      ask: 'Колко километра са (до десети)?',
      num: Math.round(nm * 1.852 * 10),
      den: 10,
      steps: [`$1$ морска миля $= 1{,}852$ km: $${nm} \\cdot 1{,}852 \\approx ${dec(Math.round(nm * 18.52) / 10)}$ km`],
    };
  }
  // Граница по паралел
  const lat = pick([30, 40, 45, 49, 60]);
  const dl = pick([5, 10, 15, 20, 25]);
  const km = 111.32 * Math.cos((lat * Math.PI) / 180) * dl;
  return {
    tex: `\\text{граница по паралела}\\ ${lat}^\\circ,\\ \\Delta\\lambda = ${dl}^\\circ`,
    ask: 'Колко километра е дълга (до km)?',
    num: Math.round(km),
    den: 1,
    steps: [`$1^\\circ$ по паралела: $111{,}3 \\cdot \\cos ${lat}^\\circ \\approx ${dec(Math.round(111.32 * Math.cos((lat * Math.PI) / 180) * 10) / 10)}$ km`, `$\\cdot\\ ${dl} \\approx ${big(Math.round(km))}$ km`],
  };
};


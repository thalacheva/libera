/** Права по метода на най-малките квадрати в log P = a − q·log r. */
export function fitRankSize(pops: number[], skipFirst = false) {
  const pts = pops.map((p, i) => [Math.log10(i + 1), Math.log10(p)]).slice(skipFirst ? 1 : 0);
  const n = pts.length;
  const mx = pts.reduce((s, [x]) => s + x, 0) / n;
  const my = pts.reduce((s, [, y]) => s + y, 0) / n;
  const sxy = pts.reduce((s, [x, y]) => s + (x - mx) * (y - my), 0);
  const sxx = pts.reduce((s, [x]) => s + (x - mx) ** 2, 0);
  const b = sxy / sxx;
  const a = my - b * mx;
  return { q: -b, p1: 10 ** a };
}

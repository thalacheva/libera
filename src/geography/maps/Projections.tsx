/** Число в LaTeX: 0.875 → 0{,}875, 25000 → 25\,000. */
const num = (v: number) => {
  const [int, frac] = v.toLocaleString('en-US', { maximumSignificantDigits: 8, useGrouping: false }).split('.');
  const grouped = int.length > 4 ? int.replace(/\B(?=(\d{3})+(?!\d))/g, '\\,') : int;
  return frac ? `${grouped}{,}${frac}` : grouped;
};
const scaleTex = (n: number) => `1 : ${num(n)}`;


const newDrill = (): Drill => {
  const kind = randInt(0, 5);
  if (kind === 0) {
    // Разлика в местното време по разликата в дължините
    const l1 = randInt(-60, 150);
    let l2 = randInt(-60, 150);
    if (l2 === l1) l2 += 7;
    const d = Math.abs(l2 - l1);
    return {
      tex: `\\lambda_1 = ${lonTex(l1)},\\ \\lambda_2 = ${lonTex(l2)}`,
      ask: 'С колко минути се различава местното слънчево време?',
      num: 4 * d,
      den: 1,
      steps: [`$\\Delta\\lambda = ${d}^\\circ$`, `На всеки градус – 4 минути: $\\Delta t = 4 \\cdot ${d} = ${4 * d}$ min.`],
    };
  }
  if (kind === 1) {
    // Дължината по разликата във времето
    const lonGreenwich = pick([15, 20, 23, 30, 45, 60, 75, 90, 105, 120, 135]) * pick([1, -1]);
    const minutes = Math.abs(lonGreenwich) * 4;
    const ahead = lonGreenwich > 0;
    return {
      tex: `12{:}00\\ \\text{UTC} ${ahead ? '-' : '+'} ${minutes}\\ \\text{min}`,
      ask: `В толкова е пладне в едно място. На колко градуса ${ahead ? 'източна' : 'западна'} дължина е то?`,
      num: Math.abs(lonGreenwich),
      den: 1,
      steps: [
        `Слънцето е в пладне там ${minutes} min ${ahead ? 'по-рано' : 'по-късно'} от Гринуич – мястото е на ${ahead ? 'изток' : 'запад'}.`,
        `$\\Delta\\lambda = \\frac{${minutes}}{4} = ${Math.abs(lonGreenwich)}^\\circ$`,
      ],
    };
  }
  if (kind === 2) {
    // Разстояние по меридиана
    const f1 = randInt(-20, 60);
    const f2 = f1 + randInt(2, 25);
    const d = f2 - f1;
    return {
      tex: `\\varphi_1 = ${f1}^\\circ,\\ \\varphi_2 = ${f2}^\\circ`,
      ask: 'Точките са на един меридиан. Колко km ги делят? (1° ≈ 111 km)',
      num: 111 * d,
      den: 1,
      steps: [`$\\Delta\\varphi = ${f2} - (${f1}) = ${d}^\\circ$`, `$s = ${d} \\cdot 111 = ${111 * d}$ km`],
    };
  }
  if (kind === 3) {
    // Морски мили
    const d = pick([0.5, 1, 1.5, 2, 3, 4, 5, 10]);
    return {
      tex: `\\Delta\\varphi = ${dec(d)}^\\circ\\ \\text{по меридиана}`,
      ask: 'Колко морски мили е това?',
      num: 60 * d,
      den: 1,
      steps: [`1 морска миля е дъгова минута: $1^\\circ = 60'$`, `$${dec(d)} \\cdot 60 = ${60 * d}$ морски мили`],
    };
  }
  if (kind === 4) {
    // Поясно време
    const [city, n] = pick(ZONES);
    const h = randInt(0, 23);
    const there = (((h + n - 2) % 24) + 24) % 24;
    return {
      tex: `\\text{София (UTC+2): } ${hh(h)}`,
      ask: `Колко часа е в ${city} (UTC${n >= 0 ? '+' : '−'}${Math.abs(n)})?`,
      num: there,
      den: 1,
      steps: [`UTC: $${h} - 2 = ${h - 2}$ → ${hh(h - 2).replace('{:}', ':')}`, `${city}: $${h - 2} ${n >= 0 ? '+' : '-'} ${Math.abs(n)}$ → ${hh(there).replace('{:}', ':')} (часовете се броят по модул 24)`],
    };
  }
  // Полет
  const [city, n] = pick(ZONES.filter(z => z[1] !== 2));
  const dep = randInt(6, 22);
  const dur = randInt(2, 13);
  const arr = (((dep + dur + n - 2) % 24) + 24) % 24;
  return {
    tex: `${hh(dep)} + ${dur}\\ \\mathrm{h}`,
    ask: `Самолет излита от София (UTC+2) в ${hh(dep).replace('{:}', ':')} и лети ${dur} h. В колко часа местно време каца в ${city} (UTC${n >= 0 ? '+' : '−'}${Math.abs(n)})?`,
    num: arr,
    den: 1,
    steps: [`По софийско време кацането е в $${dep} + ${dur} = ${dep + dur}$ ч.`, `Разлика ${city} – София: $${n} - 2 = ${n - 2}$ h`, `$${dep + dur} ${n - 2 >= 0 ? '+' : '-'} ${Math.abs(n - 2)} = ${dep + dur + n - 2}$ → ${hh(arr).replace('{:}', ':')}`],
  };
};


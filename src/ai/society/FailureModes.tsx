const reduced = (num: number, den: number) => {
  const g = gcd(num, den);
  return { num: num / g, den: den / g };
};

/** Десетично число със запетая за формула. */
const cm = (v: number) => String(Math.round(v * 1000) / 1000).replace('.', '{,}');


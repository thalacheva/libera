/** Десетично число в LaTeX: 0.45 → 0{,}45. */
const dec = (v: number) => v.toLocaleString('en-US', { maximumSignificantDigits: 6, useGrouping: false }).replace('.', '{,}');
/** Десетично число в текст: 0.45 → 0,45. */
const txt = (v: number) => dec(v).replace('{,}', ',');

const newDrill = (): Drill => {
  const kind = randInt(0, 5);
  if (kind === 0) {
    // Q10 от две скорости
    const r1 = pick([4, 5, 8, 10, 12, 20]);
    const q = pick([1.5, 2, 2.5, 3]);
    const t1 = pick([10, 15, 20, 25]);
    const r2 = r1 * q;
    return {
      tex: `v_{${t1}} = ${r1},\\ v_{${t1 + 10}} = ${dec(r2)}`,
      ask: `При ${t1} °C скоростта е ${r1}, а при ${t1 + 10} °C – ${txt(r2)} (усл. ед.). Колко е Q₁₀?`,
      num: q * 10,
      den: 10,
      steps: [`$Q_{10} = \\frac{v_{T+10}}{v_T} = \\frac{${dec(r2)}}{${r1}} = ${dec(q)}$`],
    };
  }
  if (kind === 1) {
    // Скорост след затопляне под оптимума
    const r1 = pick([3, 5, 6, 10, 15]);
    const q = pick([2, 3]);
    const dt = pick([10, 20]);
    const r2 = r1 * q ** (dt / 10);
    return {
      tex: `Q_{10} = ${q},\\ \\Delta T = ${dt}\\ ^\\circ\\mathrm{C}`,
      ask: `При 15 °C скоростта е ${r1}. Каква ще е при ${15 + dt} °C (под оптимума)?`,
      num: r2,
      den: 1,
      steps: [`$v_2 = v_1 \\cdot Q_{10}^{\\Delta T / 10} = ${r1} \\cdot ${q}^{${dt / 10}} = ${r2}$`],
    };
  }
  if (kind === 2) {
    // Михаелис–Ментен: скорост при [S] = m·Km
    const vmax = pick([40, 60, 80, 100, 120]);
    const km = pick([0.5, 1, 2, 4]);
    const m = pick([0.25, 1, 3, 4, 9]);
    const s = km * m;
    const v = (vmax * s) / (km + s);
    return {
      tex: `V_{\\max} = ${vmax},\\ K_m = ${dec(km)}\\ \\mathrm{mM}`,
      ask: `Каква е скоростта при [S] = ${txt(s)} mmol/L?`,
      num: v,
      den: 1,
      steps: [`$v = \\frac{V_{\\max}[\\mathrm{S}]}{K_m + [\\mathrm{S}]} = \\frac{${vmax} \\cdot ${dec(s)}}{${dec(km)} + ${dec(s)}} = ${dec(v)}$`],
    };
  }
  if (kind === 3) {
    // Km от една измерена скорост
    const vmax = pick([50, 80, 100, 120, 200]);
    const p = pick([0.2, 0.25, 0.4, 0.5, 0.8]);
    const s = pick([1, 2, 3, 4, 6]);
    const v = vmax * p;
    const km = (s * (1 - p)) / p;
    return {
      tex: `V_{\\max} = ${vmax},\\ v = ${dec(v)},\\ [\\mathrm{S}] = ${s}\\ \\mathrm{mM}`,
      ask: 'Колко е Km, mmol/L?',
      num: Math.round(km * 100),
      den: 100,
      steps: [`От $v = \\frac{V_{\\max}[\\mathrm{S}]}{K_m + [\\mathrm{S}]}$: $K_m = [\\mathrm{S}] \\cdot \\frac{V_{\\max} - v}{v}$`, `$K_m = ${s} \\cdot \\frac{${vmax} - ${dec(v)}}{${dec(v)}} = ${dec(km)}\\ \\mathrm{mmol/L}$`],
    };
  }
  if (kind === 4) {
    // Конкурентен инхибитор
    const km = pick([1, 2, 5]);
    const ki = pick([0.5, 1, 2]);
    const i = pick([1, 2, 4]);
    const app = km * (1 + i / ki);
    return {
      tex: `K_m = ${km},\\ K_i = ${dec(ki)},\\ [\\mathrm{I}] = ${i}`,
      ask: 'Конкурентен инхибитор. Колко е привидната Km, mmol/L?',
      num: app,
      den: 1,
      steps: [`$K_m' = K_m \\left(1 + \\frac{[\\mathrm{I}]}{K_i}\\right) = ${km} \\cdot \\left(1 + \\frac{${i}}{${dec(ki)}}\\right) = ${dec(app)}$`],
    };
  }
  // Спрягане с АТФ
  const dg = pick([14, 25, 40, 52, 70, 95]);
  const n = Math.ceil(dg / 30.5);
  return {
    tex: `\\Delta G = +${dg}\\ \\mathrm{kJ/mol}`,
    ask: 'Най-малко колко АТФ (по −30,5 kJ/mol) трябва да се хидролизират, за да протече реакцията?',
    num: n,
    den: 1,
    steps: [`Сумата трябва да е отрицателна: $${dg} - 30{,}5 \\cdot n < 0$, $n > ${dec(Math.round((dg / 30.5) * 100) / 100)}$`, `$n = ${n}$`],
  };
};


/** Десетично число в LaTeX: 0.45 → 0{,}45. */
const dec = (v: number) => v.toLocaleString('en-US', { maximumSignificantDigits: 6, useGrouping: false }).replace('.', '{,}');
/** Двоен факториел: 7!! = 7 · 5 · 3 · 1. */
const dfact = (k: number): number => (k <= 1 ? 1 : k * dfact(k - 2));
/** Произведението за двойния факториел като текст: 7 \cdot 5 \cdot 3 \cdot 1. */
const dfactTex = (k: number) => {
  const xs: number[] = [];
  for (let i = k; i >= 1; i -= 2) xs.push(i);
  return xs.join(' \\cdot ');
};


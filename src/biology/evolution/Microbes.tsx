            description="Безполовото размножаване на бактериите: кръговата хромозома се удвоява, двете копия се раздалечават, клетката се удължава и се разделя на две еднакви дъщерни клетки. Времето между две деления е времето на генерация g – при E. coli в оптимални условия около 20 min."

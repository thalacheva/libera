/** Число с десетична запетая за KaTeX. */
const dec = (v: number) => String(Number(v.toFixed(6))).replace('.', '{,}');
/** Голямо цяло число с тесни интервали за KaTeX. */
const big = (v: number) => String(v).replace(/\B(?=(\d{3})+(?!\d))/g, '\\,');


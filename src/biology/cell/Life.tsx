/** Десетично число в LaTeX: 0.45 → 0{,}45. */
const dec = (v: number) => v.toLocaleString('en-US', { maximumSignificantDigits: 6, useGrouping: false }).replace('.', '{,}');
const mu = '\\ \\mathrm{\\mu m}';
const mm = '\\ \\mathrm{mm}';

const newDrill = (): Drill => {
  const kind = randInt(0, 5);
  if (kind === 0) {
    const oc = pick([5, 10, 15]);
    const ob = pick([4, 10, 40, 100]);
    return {
      tex: `\\text{окуляр } ${oc}\\times,\\ \\text{обектив } ${ob}\\times`,
      ask: 'Общо увеличение?',
      num: oc * ob,
      den: 1,
      steps: [`Увеличенията се умножават: $M = ${oc} \\cdot ${ob} = ${oc * ob}$ пъти.`],
    };
  }
  if (kind === 1) {
    // Истински размер от размера на образа (снимка, рисунка)
    const M = pick([100, 200, 400, 500, 1000, 2000]);
    const real = pick([5, 6, 8, 10, 12, 15, 20, 25, 40, 50, 60, 75, 80, 120, 150]);
    const image = (real * M) / 1000;
    return {
      tex: `\\text{образ } ${dec(image)}${mm},\\ M = ${M}\\times`,
      ask: 'Истински размер в µm?',
      num: real,
      den: 1,
      steps: [`$${dec(image)}${mm} = ${dec(image * 1000)}${mu}$`, `$\\text{размер} = \\frac{\\text{образ}}{M} = \\frac{${dec(image * 1000)}}{${M}} = ${real}${mu}$`],
    };
  }
  if (kind === 2) {
    // Увеличение по мащабна линийка
    const L = pick([10, 20, 50, 100]);
    const M = pick([200, 500, 1000, 2000]);
    const b = (M * L) / 1000;
    return {
      tex: `\\text{линийка } ${L}${mu} \\text{ е дълга } ${dec(b)}${mm}`,
      ask: 'Колко пъти е увеличена снимката?',
      num: M,
      den: 1,
      steps: [`$${dec(b)}${mm} = ${dec(b * 1000)}${mu}$`, `$M = \\frac{${dec(b * 1000)}}{${L}} = ${M}$ пъти`],
    };
  }
  if (kind === 3) {
    // Зрителното поле намалява толкова пъти, колкото пъти расте увеличението на обектива
    const [a, b] = pick([
      [4, 10],
      [10, 40],
      [4, 40],
      [40, 100],
      [10, 100],
    ]);
    const field = pick([1.6, 1.8, 2, 2.2]) * (10 / a);
    const field2 = (field * a) / b;
    return {
      tex: `${a}\\times:\\ \\text{поле } ${dec(field)}${mm};\\quad ${b}\\times:\\ ?`,
      ask: 'Диаметър на полето при новия обектив, в µm?',
      num: Math.round(field2 * 1000),
      den: 1,
      steps: [`Обективът увеличава $\\frac{${b}}{${a}} = ${dec(b / a)}$ пъти повече – полето намалява толкова пъти.`, `$\\frac{${dec(field)}${mm}}{${dec(b / a)}} = ${dec(field2)}${mm} = ${dec(field2 * 1000)}${mu}$`],
    };
  }
  if (kind === 4) {
    // Размер на клетка: поле : брой клетки
    const [field, n] = pick([
      [1800, 12],
      [1800, 6],
      [4500, 18],
      [450, 9],
      [450, 6],
      [2000, 8],
      [180, 24],
    ]);
    return {
      tex: `\\text{поле } ${dec(field)}${mu}:\\ ${n}\\ \\text{клетки по диаметъра}`,
      ask: 'Дължина на една клетка, µm?',
      num: field,
      den: n,
      steps: [`$\\frac{${dec(field)}${mu}}{${n}} = ${dec(field / n)}${mu}$`],
    };
  }
  // Превръщане на мерни единици
  const [v, from, to, f] = pick<[number, string, string, number]>([
    [0.25, 'mm', '\\mu m', 1000],
    [0.06, 'mm', '\\mu m', 1000],
    [7.5, '\\mu m', 'nm', 1000],
    [100, 'nm', '\\mu m', 0.001],
    [2500, '\\mu m', 'mm', 0.001],
    [0.2, '\\mu m', 'nm', 1000],
  ]);
  const toText = to.replace('\\mu ', 'µ');
  return {
    tex: `${dec(v)}\\ \\mathrm{${from}} = ?\\ \\mathrm{${to}}`,
    ask: `Колко ${toText} е това?`,
    num: Math.round(v * f * 1000),
    den: 1000,
    steps: [`$1\\ \\mathrm{mm} = 1000${mu}$, $1${mu} = 1000\\ \\mathrm{nm}$`, `$${dec(v)}\\ \\mathrm{${from}} = ${dec(v * f)}\\ \\mathrm{${to}}$`],
  };
};


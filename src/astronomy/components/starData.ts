export const star = (id: string) => STARS.find(s => s.id === id)!;

/** Радиус (R☉) от светимостта и температурата: L = R² · (T / T☉)⁴. */
export const radiusOf = (s: { L: number; T: number }) => Math.sqrt(s.L) * (T_SUN / s.T) ** 2;

/** Видима величина от абсолютната и разстоянието (pc). */
export const apparent = (MV: number, d: number) => MV + 5 * Math.log10(d / 10);

/** Температура от B − V (Балестерос, 2012 – за черно тяло, приблизително). */
export const temperatureFromBV = (bv: number) => 4600 * (1 / (0.92 * bv + 1.7) + 1 / (0.92 * bv + 0.62));

/** Обратната зависимост – търсим B − V с бисекция. */
export function bvFromTemperature(T: number) {
  let lo = -0.5;
  let hi = 2.2;
  for (let i = 0; i < 40; i++) {
    const mid = (lo + hi) / 2;
    if (temperatureFromBV(mid) > T) lo = mid;
    else hi = mid;
  }
  return (lo + hi) / 2;
}


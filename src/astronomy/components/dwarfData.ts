export const AU_LIGHT_S = 499; // светлината изминава 1 AU за ~499 s

/** Време за светлината като текст. */
export function lightTime(au: number) {
  const s = au * AU_LIGHT_S;
  if (s < 3600) return `${Math.round(s / 60)} min`;
  if (s < 86400 * 2) return `${(s / 3600).toLocaleString('bg-BG', { maximumFractionDigits: 1 })} h`;
  if (s < 86400 * 365 * 0.5) return `${Math.round(s / 86400)} дни`;
  return `${(s / (86400 * 365.25)).toLocaleString('bg-BG', { maximumFractionDigits: 1 })} г.`;
}

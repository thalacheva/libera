/** Интерполира пътя за даден „прогрес“ p ∈ [0, n − 1] (по точки, логаритмично по T и L). */
export function trackAt(track: Track, p: number) {
  const n = track.points.length;
  const i = Math.min(n - 2, Math.max(0, Math.floor(p)));
  const f = Math.min(1, Math.max(0, p - i));
  const a = track.points[i];
  const b = track.points[i + 1];
  const lerpLog = (x: number, y: number) => 10 ** (Math.log10(x) + (Math.log10(y) - Math.log10(x)) * f);
  return { T: lerpLog(a.T, b.T), L: lerpLog(a.L, b.L), t: a.t + (b.t - a.t) * f, point: f < 0.5 ? a : b, index: f < 0.5 ? i : i + 1 };
}

